// config.js
// Здесь собраны настройки приложения в одном месте.
//
// .env — это текстовый файл с настройками, которые не должны попадать в Git
// (например, пароли или разные значения для компьютера ученика и учителя).
// Библиотека dotenv читает такой файл и добавляет его значения в process.env.
require('dotenv');

// Будем использовать библиотеку path для построения путей к файлам.
// Плюс в том, что она умеет создавать правильные пути для разных
// операционных систем автоматически.
const path = require('path');

// Важно: все переменные окружения изначально считываются как строки (текст),
// поэтому числовые переменные необходимо вручную переводить из строки в число.

// process.env.PORT — строка, поэтому используем Number(...) для её превращения число.
// Если переменная не задана, используется порт 3000.
const port = Number(process.env.PORT) || 3000;

// Путь к базе данных можно переопределить в .env.
// По умолчанию база лежит в папке data/app.db.
const dbPath = process.env.DB_PATH || path.join('data', 'app.db');

// __dirname — абсолютный путь к папке, в которой находится config.js.
// path.resolve делает путь к базе абсолютным независимо от того,
// из какой папки была запущена команда node.
module.exports = {
  port: port,
  dbPath: path.resolve(__dirname, dbPath),
  frontendPath: path.join(__dirname, 'frontend')
};
